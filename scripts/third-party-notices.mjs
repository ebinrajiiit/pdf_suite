#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.txt, which release builds must ship
// (docs/LICENSE-POLICY.md §4).
//
// It covers two populations: npm production dependencies, whose licence text
// comes from the installed package, and the components compiled into our wasm
// blobs, which npm knows nothing about. Those are listed in
// scripts/third-party.json and their licence texts live in notices/, fetched
// from upstream because the npm packages do not ship them.
//
// Licence text is never invented. A component with no text available is a hard
// failure, because shipping without it is the licence breach this file exists to
// prevent.
//
//   node scripts/third-party-notices.mjs [--check]
import { execSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const repoRoot = resolve(import.meta.dirname, "..");
const noticesDir = join(repoRoot, "notices");
const outFile = join(repoRoot, "THIRD_PARTY_NOTICES.txt");
const check = process.argv.includes("--check");

const LICENCE_FILES = [
  "LICENSE",
  "LICENSE.md",
  "LICENSE.txt",
  "LICENCE",
  "license",
  "license.md",
  "LICENSE-MIT",
  "LICENSE-APACHE",
];

/** The licence text a package ships, if it ships one. */
function textFromPackage(dir) {
  for (const name of LICENCE_FILES) {
    const file = join(dir, name);
    if (existsSync(file)) return readFileSync(file, "utf8").trim();
  }
  return undefined;
}

/** notices/ filenames are slugs of the component or package name. */
function slugify(name) {
  return name
    .toLowerCase()
    .replace(/\s*\(.*\)\s*/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** A licence text vendored under notices/, matched by filename prefix. */
function vendoredText(prefix) {
  if (!existsSync(noticesDir)) return undefined;
  const matches = readdirSync(noticesDir).filter((f) => f.startsWith(prefix));
  if (matches.length === 0) return undefined;
  return matches
    .sort()
    .map((f) => `--- ${f} ---\n\n${readFileSync(join(noticesDir, f), "utf8").trim()}`)
    .join("\n\n");
}

/** A licenceFile entry that names a real path in this repo. */
function textFromLicenceField(field) {
  if (!field || field.startsWith("http")) return undefined;
  // Entries may carry a trailing explanation in brackets.
  const path = field.split(" (")[0];
  const file = join(repoRoot, path);
  return existsSync(file) ? readFileSync(file, "utf8").trim() : undefined;
}

/**
 * Packages whose upstream ships no licence text. Their SPDX declaration is the
 * grant; citing it beats inventing a text. Audited in notices/declared-only.json.
 */
const declaredOnly = existsSync(join(noticesDir, "declared-only.json"))
  ? JSON.parse(readFileSync(join(noticesDir, "declared-only.json"), "utf8")).packages
  : {};

const report = JSON.parse(execSync("pnpm licenses list --prod --json", { encoding: "utf8" }));
const npmPackages = [];
for (const [licence, packages] of Object.entries(report)) {
  for (const pkg of packages) {
    npmPackages.push({
      name: pkg.name,
      versions: pkg.versions.join(", "),
      licence,
      homepage: pkg.homepage,
      // Some packages ship no licence file at all; the text is then vendored
      // under notices/npm-<name>-*, fetched from upstream.
      text:
        pkg.paths?.map(textFromPackage).find(Boolean) ?? vendoredText(`npm-${slugify(pkg.name)}-`),
    });
  }
}
npmPackages.sort((a, b) => a.name.localeCompare(b.name));

const thirdParty = JSON.parse(
  readFileSync(join(repoRoot, "scripts/third-party.json"), "utf8"),
).components;
// A component we do not distribute needs no notice. Keeping them in the file
// with "shipped": false records the decision instead of hiding it.
const shipped = thirdParty.filter((c) => c.shipped !== false);
const notShipped = thirdParty.filter((c) => c.shipped === false);

const missing = [];
const sections = [];

sections.push(
  [
    "THIRD-PARTY NOTICES",
    "",
    "This product includes the software listed below. Each component remains under",
    "its own licence; the full text of each follows its entry.",
    "",
    "Generated by scripts/third-party-notices.mjs. Do not edit by hand.",
  ].join("\n"),
);

sections.push(
  [
    "=".repeat(78),
    "Bundled components (compiled into our WebAssembly builds)",
    "=".repeat(78),
  ].join("\n"),
);

for (const component of shipped) {
  // notices/<slug>-* holds the text for components npm cannot describe.
  const slug = slugify(component.name);
  const text = vendoredText(slug) ?? textFromLicenceField(component.licenceFile);

  if (!text) missing.push(`${component.name} (expected notices/${slug}-*)`);

  sections.push(
    [
      "-".repeat(78),
      component.name,
      `Licence: ${component.licence}`,
      `Version: ${component.version}`,
      `Source:  ${component.source}`,
      component.notes ? `Notes:   ${component.notes}` : undefined,
      "",
      text ?? "*** LICENCE TEXT MISSING ***",
    ]
      .filter((line) => line !== undefined)
      .join("\n"),
  );
}

if (notShipped.length > 0) {
  sections.push(
    [
      "-".repeat(78),
      "Recorded but not distributed, so no notice is required:",
      ...notShipped.map((c) => `  ${c.name} — ${c.licence}`),
    ].join("\n"),
  );
}

sections.push(["=".repeat(78), "npm production dependencies", "=".repeat(78)].join("\n"));

for (const pkg of npmPackages) {
  const exception = declaredOnly[pkg.name];
  if (!pkg.text && !exception) {
    missing.push(`${pkg.name} (no licence file in the installed package)`);
  }
  const body = pkg.text
    ? pkg.text
    : exception
      ? [
          `Licensed under ${pkg.licence}, declared by the package rather than by a`,
          "licence file: the upstream project publishes none.",
          "",
          `  ${exception.evidence}`,
          `  ${exception.reason}`,
          `  Checked: ${exception.checked}`,
        ].join("\n")
      : "*** LICENCE TEXT MISSING ***";

  sections.push(
    [
      "-".repeat(78),
      `${pkg.name} ${pkg.versions}`,
      `Licence: ${pkg.licence}`,
      pkg.homepage ? `Home:    ${pkg.homepage}` : undefined,
      "",
      body,
    ]
      .filter((line) => line !== undefined)
      .join("\n"),
  );
}

const content = `${sections.join("\n\n")}\n`;

if (missing.length > 0) {
  console.error("Licence text missing, so the notices file cannot be shipped:");
  for (const item of missing) console.error(`  - ${item}`);
  console.error("\nFetch the upstream text into notices/ and run this again.");
  process.exit(1);
}

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current !== content) {
    console.error("THIRD_PARTY_NOTICES.txt is out of date. Run: pnpm notices");
    process.exit(1);
  }
  console.log(
    `THIRD_PARTY_NOTICES.txt is current: ${shipped.length} bundled components, ` +
      `${npmPackages.length} npm packages.`,
  );
} else {
  writeFileSync(outFile, content);
  console.log(
    `Wrote THIRD_PARTY_NOTICES.txt: ${shipped.length} bundled components, ` +
      `${npmPackages.length} npm packages, ${(content.length / 1024).toFixed(0)} kB.`,
  );
}
